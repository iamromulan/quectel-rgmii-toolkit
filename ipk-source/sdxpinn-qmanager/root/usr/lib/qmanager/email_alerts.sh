#!/bin/sh
# =============================================================================
# email_alerts.sh — Email Alert Library for QManager
# =============================================================================
# Sourced by qmanager_poller and CGI scripts. Detects prolonged internet
# downtime and sends a recovery email (with downtime details) via msmtp
# once connectivity is restored.
#
# Dependencies: jq, msmtp, qlog_* functions (optional)
# Install location: /usr/lib/qmanager/email_alerts.sh
#
# Global variables used from poller:
#   Read: conn_internet_available ("true"/"false"/"null")
#
# Config:  /etc/qmanager/email_alerts.json
# Log:     /tmp/qmanager_email_log.json (NDJSON, max 100 entries)
# msmtp:   /etc/qmanager/msmtprc (generated by CGI on save)
# Reload:  /tmp/qmanager_email_reload (flag file, touched by CGI)
# =============================================================================

[ -n "$_EMAIL_ALERTS_LOADED" ] && return 0
_EMAIL_ALERTS_LOADED=1

# Single alert wait resolver (cq_alert_after_min). Guarded: BusyBox ash exits
# when `.` cannot find its file.
[ -f /usr/lib/qmanager/conn_state.sh ] && . /usr/lib/qmanager/conn_state.sh

# --- Constants ---------------------------------------------------------------
_EA_CONFIG="/etc/qmanager/email_alerts.json"
_EA_MSMTP_CONFIG="/etc/qmanager/msmtprc"
_EA_LOG_FILE="/tmp/qmanager_email_log.json"
_EA_RELOAD_FLAG="/tmp/qmanager_email_reload"
_EA_MAX_LOG=100

# --- State (populated by email_alerts_init / _ea_read_config) ----------------
# Downtime tracking now lives in alert_engine.sh; this lib only owns the
# channel transport config + send/log helpers. The engine reads _ea_enabled
# and _ea_threshold_minutes to gate + threshold the email channel.
_ea_enabled="false"
_ea_sender=""
_ea_recipient=""
_ea_app_password=""
_ea_threshold_minutes=5

# =============================================================================
# _ea_read_config — Read settings from config JSON
# =============================================================================
_ea_read_config() {
    if [ ! -f "$_EA_CONFIG" ]; then
        _ea_enabled="false"
        return 1
    fi

    _ea_enabled=$(jq -r '(.enabled) | if . == null then "false" else tostring end' "$_EA_CONFIG" 2>/dev/null)
    _ea_sender=$(jq -r '.sender_email // ""' "$_EA_CONFIG" 2>/dev/null)
    _ea_recipient=$(jq -r '.recipient_email // ""' "$_EA_CONFIG" 2>/dev/null)
    _ea_app_password=$(jq -r '.app_password // ""' "$_EA_CONFIG" 2>/dev/null)
    _ea_threshold_minutes=$(jq -r '.threshold_minutes // 5' "$_EA_CONFIG" 2>/dev/null)
    # The wait is one value owned by Connection Quality; the channel key is a fallback.
    if command -v cq_alert_after_min >/dev/null 2>&1; then
        cq_alert_after_min
        _ea_threshold_minutes="$CQ_ALERT_AFTER_MIN"
    fi

    # Validate
    if [ "$_ea_enabled" != "true" ]; then
        _ea_enabled="false"
        return 0
    fi
    if [ -z "$_ea_sender" ] || [ -z "$_ea_recipient" ] || [ -z "$_ea_app_password" ]; then
        _ea_enabled="false"
        return 1
    fi
    return 0
}

# =============================================================================
# email_alerts_init — Called once at poller startup
# =============================================================================
email_alerts_init() {
    _ea_read_config
    if [ "$_ea_enabled" = "true" ]; then
        qlog_info "Email alerts enabled: sender=$_ea_sender recipient=$_ea_recipient threshold=${_ea_threshold_minutes}m"
    else
        qlog_info "Email alerts disabled or not configured"
    fi
}

# =============================================================================
# email_alert_emit <event> <secs> — engine-driven send + log (one message)
# =============================================================================
# Called by alert_engine.sh. The engine owns downtime tracking, thresholds,
# routing and suppression (including the conn_during_recovery gate email used
# to be missing). This function only builds + sends.
#
# connection_lost is NEVER routed to email (email is incapable during an
# outage — no internet/DNS), so it is a deliberate no-op success. Only
# connection_restored builds and sends the recovery email.
#
# Returns: 0 = sent (or intentional no-op), 1 = send failed.
email_alert_emit() {
    local event="$1"
    local secs="$2"
    local cause="$3"
    local count="$4"
    local start_epoch
    local start_time
    local dur_text
    local html
    local subject
    local attempt
    local max_attempts
    local retry_delay

    # connection_lost is never capable for email (no internet/DNS during an
    # outage) — deliberate no-op success. connection_restored and reboot both
    # arrive post-recovery, when email can deliver.
    if [ "$event" != "connection_restored" ] && [ "$event" != "reboot" ]; then
        return 0
    fi

    # The engine measures duration with the monotonic clock. The email body only
    # needs a human-readable stamp, so reconstruct it from wall-clock now minus
    # the elapsed seconds. A NITZ step can skew this display value slightly, but
    # it never affects whether the email is sent (decided monotonically upstream).
    start_epoch=$(( $(date +%s) - secs ))
    start_time=$(date -d "@$start_epoch" "+%Y-%m-%d %H:%M:%S" 2>/dev/null) || \
        start_time=$(awk "BEGIN{print strftime(\"%Y-%m-%d %H:%M:%S\",$start_epoch)}" 2>/dev/null) || \
        start_time="$start_epoch"
    dur_text=$(_ea_format_duration "$secs")

    if [ "$event" = "reboot" ]; then
        if [ "$cause" = "storm" ]; then
            subject="Modem Reboot Loop"
            html=$(_ea_build_reboot_html "storm" "$dur_text" "$count")
        else
            subject="Modem Rebooted"
            html=$(_ea_build_reboot_html "$cause" "$dur_text" "")
        fi
    else
        subject="Connection Recovered"
        html=$(_ea_build_recovery_html "$start_time" "$dur_text" "$_ea_threshold_minutes")
    fi

    # Send with retry — DNS may not be ready immediately after recovery.
    attempt=0
    max_attempts=3
    retry_delay=10

    while [ "$attempt" -lt "$max_attempts" ]; do
        attempt=$((attempt + 1))

        if [ "$attempt" -gt 1 ]; then
            qlog_info "Email alerts: retry $attempt/$max_attempts after ${retry_delay}s..."
            sleep "$retry_delay"
        fi

        if _ea_do_send "$subject" "$html"; then
            _ea_log_event "$event" "sent" "$_ea_recipient"
            return 0
        fi

        qlog_warn "Email alerts: send attempt $attempt/$max_attempts failed"
    done

    qlog_error "Email alerts: all $max_attempts send attempts failed"
    _ea_log_event "$event" "failed" "$_ea_recipient"
    return 1
}

# =============================================================================
# _ea_send_test_email — Send a test email (called by CGI)
# =============================================================================
_ea_send_test_email() {
    local html
    html=$(_ea_build_test_html)

    if _ea_do_send "Test Alert" "$html"; then
