[ -n "$_EVENTS_LOADED" ] && return 0
_EVENTS_LOADED=1

PCI_STATE_FILE="/tmp/qmanager_pci_state.json"

# Append a single event to the events file (NDJSON — one JSON per line)
# Note: All message content is generated by us (band names, PCI numbers, etc.)
# so no user-input escaping is needed.
append_event() {
    local etype="$1" message="$2" severity="${3:-info}"
    local ts
    ts=$(date +%s)

    jq -n -c \
        --argjson ts "$ts" \
        --arg type "$etype" \
        --arg message "$message" \
        --arg severity "$severity" \
        '{timestamp: $ts, type: $type, message: $message, severity: $severity}' >> "$EVENTS_FILE"

    # Trim to max entries
    local count
    count=$(wc -l < "$EVENTS_FILE" 2>/dev/null || echo 0)
    if [ "$count" -gt "$MAX_EVENTS" ]; then
        local tmp="${EVENTS_FILE}.tmp"
        if tail -n "$MAX_EVENTS" "$EVENTS_FILE" > "$tmp" 2>/dev/null; then
            mv "$tmp" "$EVENTS_FILE" 2>/dev/null || rm -f "$tmp"
        else
            rm -f "$tmp"
        fi
    fi

    qlog_info "EVENT [${etype}] ${message}"
}

# ---------------------------------------------------------------------------
# Helper functions for detailed event messages
# ---------------------------------------------------------------------------
# These are only called when events actually fire (state changes), so the
# jq overhead is negligible — events are rare compared to 2s poll cycles.

# Get compact band list for a technology from carrier_components JSON
# Usage: bands=$(_ev_bands "LTE" "$t2_carrier_components") => "B3 + B7 + B28"
_ev_bands() {
    local tech="$1" cc="$2"
    [ -z "$cc" ] || [ "$cc" = "[]" ] && return
    printf '%s' "$cc" | jq -r --arg t "$tech" \
        '[.[] | select(.technology == $t) | .band] | if length > 0 then join(" + ") else empty end' 2>/dev/null
}

# Get band summary with total bandwidth for a technology
# Usage: summary=$(_ev_band_summary "LTE" "$t2_carrier_components") => "B3 + B7 + B28, 40 MHz"
_ev_band_summary() {
    local tech="$1" cc="$2"
    [ -z "$cc" ] || [ "$cc" = "[]" ] && return
    printf '%s' "$cc" | jq -r --arg t "$tech" '
        [.[] | select(.technology == $t)] |
        if length == 0 then empty
        else
            (map(.band) | join(" + ")) as $bands |
            (map(.bandwidth_mhz) | add) as $bw |
            if $bw > 0 then "\($bands), \($bw) MHz"
            else $bands end
        end
    ' 2>/dev/null
}

# Compute added/removed bands between prev and current carrier_components.
# Sets global: _diff_added, _diff_removed (comma-separated band strings)
# Usage: _ev_ca_diff "LTE" "$prev_ev_carrier_components" "$t2_carrier_components"
_ev_ca_diff() {
    local tech="$1" prev="$2" curr="$3"
    _diff_added=""
    _diff_removed=""
    [ -z "$prev" ] && prev="[]"
    [ -z "$curr" ] && curr="[]"

    # One line, "added|removed": $(...) drops an empty last line, which made a
    # pure addition read as "(+B7, -B7)".
    local result
    result=$(jq -rn --arg t "$tech" --argjson p "$prev" --argjson c "$curr" '
        ([$c[] | select(.technology == $t) | .band] - [$p[] | select(.technology == $t) | .band] | join(", "))
        + "|" +
        ([$p[] | select(.technology == $t) | .band] - [$c[] | select(.technology == $t) | .band] | join(", "))
    ' 2>/dev/null)

    case "$result" in *"|"*) ;; *) return ;; esac
    _diff_added="${result%%|*}"
    _diff_removed="${result#*|}"
}

# ---------------------------------------------------------------------------
# Settle debounce for discrete radio identifiers
# ---------------------------------------------------------------------------
# A raw "this sample != last sample" comparison reports every one-sample
# flicker. On the RM520N-GL the secondary carrier drops out of AT+QCAINFO for a
# single sample every 30-80 s, so the event ring filled with "CA deactivated" /
# "CA activated" pairs a few seconds apart (281 of 300 slots in one capture).
# _ev_settle only announces a value after it has held for EV_SETTLE_SAMPLES
# consecutive real observations, and a blank is no observation at all (it
# leaves every counter as it was, so an outage cannot reset a settle).
#
# A value that oscillates faster than the settle window never settles, so a
# hold-only rule would go SILENT on the most broken radio. Churn is therefore
# counted, and rc 2 tells the caller to report the instability itself.
#
# Usage:
#   _ev_settle <channel> <current-value> [sticky]; rc=$?
#     rc 0 -> settled onto a new value; read $_EV_SETTLED_TO / $_EV_SETTLED_FROM
#     rc 1 -> nothing to report (blank, still settling, unchanged, or the
#             first settle after a cold start, which is adopted silently)
#     rc 2 -> churning; $_EV_FLAP_N is the count in this window
#   "sticky": settling back onto the announced value keeps the churn window and
#   the report latch, so one-sample dips add up and a churn episode is
#   reported once; the caller (_ev_ca_check) ends the episode.
#
# <channel> must be a bare identifier; it is interpolated into variable names.
# State lives in poller globals and is not persisted: a poller restart
# re-settles, which costs one settle window of silence.
EV_SETTLE_SAMPLES="${EV_SETTLE_SAMPLES:-3}"
EV_FLAP_THRESHOLD="${EV_FLAP_THRESHOLD:-6}"
EV_FLAP_WINDOW="${EV_FLAP_WINDOW:-300}"

_ev_settle() {
    local _ch="$1" _cur="$2" _sticky="${3:-}"
    local _hold _holdn _last _flapn _flapt _now
    _EV_SETTLED_FROM=""
    _EV_SETTLED_TO=""
    _EV_FLAP_N=0

    [ -z "$_cur" ] && return 1

    eval "_hold=\${_ev_hold_${_ch}:-}"
    eval "_holdn=\${_ev_holdn_${_ch}:-0}"
    eval "_last=\${_ev_last_${_ch}:-}"

    if [ "$_cur" = "$_hold" ]; then
        _holdn=$((_holdn + 1))
    else
        # A new candidate. It is churn unless it is the announced value coming back.
        if [ "$_cur" != "$_last" ]; then
            eval "_flapn=\${_ev_flapn_${_ch}:-0}"
            eval "_flapt=\${_ev_flapt_${_ch}:-0}"
            _now=$(date +%s)
            if [ $((_now - _flapt)) -ge "$EV_FLAP_WINDOW" ]; then
                _flapn=1
                _flapt="$_now"
            else
                _flapn=$((_flapn + 1))
            fi
            eval "_ev_flapn_${_ch}=\$_flapn"
            eval "_ev_flapt_${_ch}=\$_flapt"
            eval "_ev_chg_${_ch}=\$_now"
        fi
        _hold="$_cur"
        _holdn=1
    fi

    eval "_ev_hold_${_ch}=\$_hold"
    eval "_ev_holdn_${_ch}=\$_holdn"

    if [ "$_holdn" -ge "$EV_SETTLE_SAMPLES" ]; then
        # Settled: clear the churn window and latch so a later episode is
        # reported promptly. A sticky channel clears them only on a real change.
        eval "_ev_last_${_ch}=\$_cur"
        if [ -z "$_sticky" ] || { [ -n "$_last" ] && [ "$_cur" != "$_last" ]; }; then
            eval "_ev_flapn_${_ch}=0"
            eval "_ev_flapr_${_ch}=0"
        fi
        if [ -n "$_last" ] && [ "$_cur" != "$_last" ]; then
            _EV_SETTLED_FROM="$_last"
            _EV_SETTLED_TO="$_cur"
            return 0
        fi
        return 1
    fi

    # Still unsettled: report churn at most once per window (once per episode
    # when sticky). The latch is separate from the counter, which refills fast.
    eval "_flapn=\${_ev_flapn_${_ch}:-0}"
    if [ "$_flapn" -ge "$EV_FLAP_THRESHOLD" ]; then
        local _flapr
        eval "_flapr=\${_ev_flapr_${_ch}:-0}"
        _now=$(date +%s)
        if [ "$_flapr" -eq 0 ] || { [ -z "$_sticky" ] && [ $((_now - _flapr)) -ge "$EV_FLAP_WINDOW" ]; }; then
            _EV_FLAP_N="$_flapn"
            eval "_ev_flapn_${_ch}=0"
            eval "_ev_flapt_${_ch}=\$_now"
            eval "_ev_flapr_${_ch}=\$_now"
            return 2
        fi
    fi

    return 1
}

# CA state for one tech (channel lte_ca / nr_ca), keyed on the SCC count through
# a sticky settle. No observation when QCAINFO gave no reading (an empty carrier
# list) or on the deep polling tier (QCAINFO is skipped there and the CA fields
# keep their last values, which must not count as fresh samples).
_ev_ca_check() {
    local _ch="$1" _tech="$2" _count="$3"
    local _obs="" _rc _base _bands _hold _holdn _last _flapr _chg _now
    if [ "${ap_tier:-}" != "deep" ] && \
       [ -n "$t2_carrier_components" ] && [ "$t2_carrier_components" != "[]" ]; then
        _obs="${_count:-0}"
        case "$_obs" in *[!0-9]*) _obs="" ;; esac
    fi

    _ev_settle "$_ch" "$_obs" sticky; _rc=$?
    eval "_base=\${_ev_cabase_${_ch}:-}"

    if [ "$_rc" -eq 0 ]; then
        if [ "$_EV_SETTLED_FROM" = "0" ]; then
            local _summary
            _summary=$(_ev_band_summary "$_tech" "$t2_carrier_components")
            append_event "ca_change" \
                "$_tech CA activated${_summary:+: $_summary} ($((_EV_SETTLED_TO + 1)) carriers)" "info"
        elif [ "$_EV_SETTLED_TO" = "0" ]; then
            local _single="" _pband
            if [ "$_tech" = "NR" ]; then _pband="$nr_band"; else _pband="$lte_band"; fi
            [ -n "$_pband" ] && _single=" — single carrier ($_pband)"
            append_event "ca_change" "$_tech CA deactivated${_single}" "warning"
        else
            local _sev="info" _detail="" _parts=""
            [ "$_EV_SETTLED_TO" -lt "$_EV_SETTLED_FROM" ] && _sev="warning"
            # Diff against the carriers last announced, not the previous sample.
            _ev_ca_diff "$_tech" "$_base" "$t2_carrier_components"
            if [ -n "$_diff_added" ] || [ -n "$_diff_removed" ]; then
                [ -n "$_diff_added" ] && _parts="+${_diff_added}"
                if [ -n "$_diff_removed" ]; then
                    [ -n "$_parts" ] && _parts="$_parts, "
                    _parts="${_parts}-${_diff_removed}"
                fi
                _detail=" ($_parts)"
            else
                _bands=$(_ev_bands "$_tech" "$t2_carrier_components")
                [ -n "$_bands" ] && _detail=" (now $_bands)"
            fi
            append_event "ca_change" \
                "$_tech carriers changed from $((_EV_SETTLED_FROM + 1)) to $((_EV_SETTLED_TO + 1))${_detail}" "$_sev"
        fi
    elif [ "$_rc" -eq 2 ]; then
        append_event "ca_change" "$_tech CA churn detected" "warning"
    fi

    # Below runs only while settled on the announced value.
    [ -z "$_obs" ] && return 0
    eval "_hold=\${_ev_hold_${_ch}:-}; _holdn=\${_ev_holdn_${_ch}:-0}; _last=\${_ev_last_${_ch}:-}"
    { [ "$_hold" = "$_last" ] && [ "$_holdn" -ge "$EV_SETTLE_SAMPLES" ]; } || return 0
    eval "_ev_cabase_${_ch}=\$t2_carrier_components"

    # A churn episode ends after a full window with no candidate change.
    eval "_flapr=\${_ev_flapr_${_ch}:-0}; _chg=\${_ev_chg_${_ch}:-0}"
    [ "$_flapr" -eq 0 ] && return 0
    _now=$(date +%s)
    [ $((_now - _chg)) -ge "$EV_FLAP_WINDOW" ] || return 0
    eval "_ev_flapr_${_ch}=0; _ev_flapn_${_ch}=0"
    if [ "$_last" = "0" ]; then
        append_event "ca_change" "$_tech CA settled inactive" "warning"
    else
        _bands=$(_ev_bands "$_tech" "$t2_carrier_components")
        append_event "ca_change" "$_tech CA settled${_bands:+ on $_bands}" "info"
    fi
}

# Build a short network context string from current state
# Output: "5G-NSA: B3 + N41" or "LTE: B3" or "5G-SA: N41"
# _ev_net_context_set puts it in the global _EV_CTX (no subshell fork);
# _ev_net_context is the echo form, kept for compatibility.
_ev_net_context_set() {
    _EV_CTX=""
    if [ -n "$lte_band" ] && [ "$nr_state" = "connected" ] && [ -n "$nr_band" ]; then
        _EV_CTX="${network_type}: ${lte_band} + ${nr_band}"
    elif [ "$nr_state" = "connected" ] && [ -n "$nr_band" ]; then
        _EV_CTX="${network_type}: ${nr_band}"
    elif [ -n "$lte_band" ]; then
        _EV_CTX="${network_type}: ${lte_band}"
    elif [ -n "$network_type" ]; then
        _EV_CTX="$network_type"
    fi
}

_ev_net_context() {
    _ev_net_context_set
    [ -n "$_EV_CTX" ] && echo "$_EV_CTX"
    return 0
}

# _ev_gt <value> <threshold>: exit 0 iff value > threshold, exactly as the
# former `echo value | awk -v t=threshold '{exit !($1 > t)}'` decided it.
# A plain unsigned decimal against a plain unsigned integer is compared with
# shell arithmetic (no fork); anything else (negative, exponent, "null", text,
# padded zeros...) goes to awk so awk's own numeric/string rules still decide.
_ev_gt() {
    local _g_int
    local _g_frac
    case "$1" in
        ''|*[!0-9.]*|.*|*.*.*|0[0-9]*) ;;
        *)
            case "$2" in
                ''|*[!0-9]*|0[0-9]*) ;;
                *)
                    if [ "${#1}" -le 15 ] && [ "${#2}" -le 15 ]; then
                        _g_int="${1%%.*}"
                        _g_frac=""
                        case "$1" in *.*) _g_frac="${1#*.}" ;; esac
                        if [ "$_g_int" -gt "$2" ]; then
                            return 0
                        elif [ "$_g_int" -lt "$2" ]; then
                            return 1
                        fi
                        # Integer parts equal: greater only with a non-zero fraction.
                        case "$_g_frac" in
                            *[!0]*) return 0 ;;
                        esac
                        return 1
                    fi
                    ;;
            esac
            ;;
    esac
    echo "$1" | awk -v t="$2" '{exit !($1 > t)}'
}

# Snapshot current state into prev_ev_* variables (called once after first parse)
snapshot_event_state() {
    prev_ev_network_type="$network_type"
    # Band and PCI keep their last known good value across a blank reading:
    # parse_serving_cell blanks them whenever AT+QENG gives no usable line
    # (every service drop), and copying that blank destroyed the baseline (the
    # "was ..." clause of "5G NR anchor lost" went empty exactly then).
    prev_ev_lte_band="${lte_band:-$prev_ev_lte_band}"
    prev_ev_lte_pci="${lte_pci:-$prev_ev_lte_pci}"
    prev_ev_nr_band="${nr_band:-$prev_ev_nr_band}"
    prev_ev_nr_pci="${nr_pci:-$prev_ev_nr_pci}"
    prev_ev_nr_state="$nr_state"
    prev_ev_modem_reachable="$modem_reachable"
    # prev_ev_internet is owned by detect_data_connection_events.
    prev_ev_ca_active="$t2_ca_active"
    prev_ev_ca_count="$t2_ca_count"
    prev_ev_nr_ca_active="$t2_nr_ca_active"
    prev_ev_nr_ca_count="$t2_nr_ca_count"
    prev_ev_service_status="$service_status"
    prev_ev_cfun="$t1_cfun"
    prev_ev_carrier_components="$t2_carrier_components"
    _ev_scc_sig "$t2_carrier_components"
    prev_ev_scc_sig="$_EV_SCC_SIG"
}

# _ev_scc_sig <carrier_components JSON>: "tech band pci;" for every SCC entry,
# in order, into _EV_SCC_SIG. Builtins only. Relies on the fixed key order that
# parse_ca_info emits ({"type":..,"technology":..,"band":..,"earfcn":..,
# "bandwidth_mhz":..,"pci":..,...}).
prev_ev_scc_sig=""
_ev_scc_sig() {
    local _r
    local _o
    local _t
    local _b
    local _p
    _EV_SCC_SIG=""
    _r="$1"
    while :; do
        case "$_r" in
            *'{"type":"SCC",'*) ;;
            *) break ;;
        esac
        _r="${_r#*'{"type":"SCC",'}"
        _o="${_r%%'}'*}"
        _t="${_o#*'"technology":'}"
        _t="${_t%%,*}"
        _b="${_o#*'"band":'}"
        _b="${_b%%,*}"
        _p="${_o#*'"pci":'}"
        _p="${_p%%,*}"
        _EV_SCC_SIG="${_EV_SCC_SIG}${_t} ${_b} ${_p};"
    done
}

# ---------------------------------------------------------------------------
# SCC PCI change detection via temp JSON
# ---------------------------------------------------------------------------
# Compares current t2_carrier_components against saved state in PCI_STATE_FILE.
# Only called when t2_carrier_components string has changed (Tier 2 refresh).
detect_scc_pci_changes() {
    local prev_sccs curr_sccs

    # Build current SCC list: tech+band+pci for SCC entries only
    curr_sccs=$(printf '%s' "$t2_carrier_components" | \
        jq -c '[.[] | select(.type == "SCC") | {tech: .technology, band: .band, pci: .pci}]' 2>/dev/null)
    [ -z "$curr_sccs" ] && curr_sccs="[]"

    # Read previous state from file
    if [ -f "$PCI_STATE_FILE" ]; then
        prev_sccs=$(cat "$PCI_STATE_FILE" 2>/dev/null)
        [ -z "$prev_sccs" ] && prev_sccs="[]"
    else
        # First run — save current state, no events
        printf '%s\n' "$curr_sccs" > "$PCI_STATE_FILE"
        return
    fi

    # Compare each current SCC against previous (matched by tech+band)
    local i=0
    local curr_count
    curr_count=$(printf '%s' "$curr_sccs" | jq 'length')

    while [ "$i" -lt "$curr_count" ]; do
        local c_tech c_band c_pci p_pci
        c_tech=$(printf '%s' "$curr_sccs" | jq -r ".[$i].tech")
        c_band=$(printf '%s' "$curr_sccs" | jq -r ".[$i].band")
        c_pci=$(printf '%s' "$curr_sccs" | jq -r ".[$i].pci")

        # Find matching entry in previous state
        p_pci=$(printf '%s' "$prev_sccs" | \
            jq -r --arg t "$c_tech" --arg b "$c_band" \
            '[.[] | select(.tech == $t and .band == $b)] | .[0].pci | if . == null then empty else tostring end')

        # If previous PCI exists and differs, emit event
        if [ -n "$p_pci" ] && [ "$p_pci" != "null" ] && [ "$p_pci" != "$c_pci" ]; then
            append_event "scc_pci_change" \
                "$c_tech $c_band SCC cell handoff (PCI: $p_pci -> $c_pci)" "info"
        fi

        i=$((i + 1))
    done

    # Save current state for next comparison
    printf '%s\n' "$curr_sccs" > "$PCI_STATE_FILE"
}

# ---------------------------------------------------------------------------
# Link and quality transitions: the ONE place they are decided
# ---------------------------------------------------------------------------
# Called by the poller once per cycle, right after read_ping_data and before
# alert_engine_check, from the always-run local block (it needs no modem, so
# it keeps the base cadence on every adaptive-polling tier). alert_engine.sh
# has no edge detector of its own: it follows ev_link_state, so the Activity
# feed and the alert channels can never disagree about an outage.
#
#   ev_link_state  "down" | "up" | ""  ("" = stale/unknown only)
#
# Rules, in order:
#   * It follows the ping daemon's reachable verdict (conn_internet_available),
#     never conn_status ("recovery" would mask it), so a watchdog-fixed outage
#     still logs internet_restored.
#   * Stale or unknown ping data is no transition: all state stays frozen.
#   * The first reading after a cold start is adopted silently.
#   * The first true->false edge always logs internet_lost, even when the
#     watchdog raised its recovery flag before the poller saw the drop. Only a
#     repeat drop after a restore inside the same recovery window is held (a
#     recovery tier flapping the link), so one outage logs exactly one pair.
#   * Quality (latency/loss) is frozen while the link is down, debounced on
#     entry AND exit, and entry is held for one history window after a restore
#     (the outage nulls are still in it) and while the daemon is counting
#     failures (the run-up to a down verdict).
ev_link_state=""
ev_hold_until=""
ev_recov_restored=""   # "true": the link was restored inside the current recovery window

_ev_set_link_state() {
    case "$prev_ev_internet" in
        false) ev_link_state="down" ;;
        true)  ev_link_state="up" ;;
        *)     ev_link_state="" ;;
    esac
}

# Monotonic seconds into _EV_UP ("" if unreadable).
_ev_uptime() {
    _EV_UP=""
    { read -r _EV_UP _ev_idle < /proc/uptime; } 2>/dev/null
    _EV_UP="${_EV_UP%%.*}"
    case "$_EV_UP" in ''|*[!0-9]*) _EV_UP="" ;; esac
}

# After a restore, hold quality ENTRY for one history window.
_ev_arm_hold() {
    local _w=300
    case "${CONN_HISTORY_SIZE:-}${conn_history_interval:-}" in
        ''|*[!0-9]*) ;;
        *) _w=$(( ${CONN_HISTORY_SIZE:-0} * ${conn_history_interval:-0} )) ;;
    esac
    [ "$_w" -gt 0 ] || _w=300
    _ev_uptime
    if [ -n "$_EV_UP" ]; then ev_hold_until=$((_EV_UP + _w)); else ev_hold_until=""; fi
}

# True while quality entry is held. Exits are never held.
_ev_entry_held() {
    [ "${CQ_STREAK_FAIL:-0}" -gt 0 ] 2>/dev/null && return 0
    [ -n "$ev_hold_until" ] || return 1
    _ev_uptime
    [ -n "$_EV_UP" ] && [ "$_EV_UP" -lt "$ev_hold_until" ]
}

detect_data_connection_events() {
    case "$prev_ev_internet" in true|false) ;; *) prev_ev_internet="" ;; esac

    _ev_set_link_state

    # Stale or unknown ping data is no transition: all state stays frozen.
    case "$conn_internet_available" in true|false) ;; *) return 0 ;; esac

    # First reading after a cold start is adopted silently.
    [ -z "$prev_ev_internet" ] && prev_ev_internet="$conn_internet_available"

    # The recovery window ends with the daemon's flag; its restore marker goes with it.
    [ "$conn_during_recovery" = "true" ] || ev_recov_restored=""

    if [ "$conn_internet_available" != "$prev_ev_internet" ]; then
        if [ "$conn_internet_available" = "true" ]; then
            local restore_ctx=""
            if [ "$conn_latency" != "null" ] && [ -n "$conn_latency" ]; then
                restore_ctx=" (latency: ${conn_latency}ms)"
            fi
            append_event "internet_restored" "Internet connectivity restored${restore_ctx}" "info"
            prev_ev_internet="true"
            [ "$conn_during_recovery" = "true" ] && ev_recov_restored="true"
            _ev_arm_hold
        elif [ "$ev_recov_restored" != "true" ]; then
            local net_ctx
            _ev_net_context_set
            net_ctx="$_EV_CTX"
            local lost_detail=""
            [ -n "$net_ctx" ] && lost_detail=" ($net_ctx)"
            append_event "internet_lost" "Internet connectivity lost${lost_detail}" "warning"
            prev_ev_internet="false"
        fi
    fi
    _ev_set_link_state

    # While the link is down the outage is the record: quality is frozen.
    [ "$conn_internet_available" = "true" ] || return 0

    local _held=0
    _ev_entry_held && _held=1

    # --- Latency: configured cut, debounce on entry and on exit ---
    # Thresholds come from quecmanager.quality_thresholds via the poller's
    # resolve_quality_thresholds(), default-guarded to the "tolerant" preset.
    # Basis = WINDOWED AVERAGE (conn_avg_latency), the same field the watchdog
    # compares, not the single last RTT. "null" (too few samples) is no reading.
    local _lat_threshold="${QUALITY_LAT_THRESHOLD:-250}"
    local _lat_debounce="${QUALITY_LAT_DEBOUNCE:-3}"
    if [ "$conn_avg_latency" != "null" ] && [ -n "$conn_avg_latency" ]; then
        if _ev_gt "$conn_avg_latency" "$_lat_threshold"; then
            ev_lat_clear_streak=0
            if [ "$_held" = "1" ]; then
                ev_high_lat_streak=0
            elif [ "$ev_lat_alerted" != "true" ]; then
                ev_high_lat_streak=$((ev_high_lat_streak + 1))
                if [ "$ev_high_lat_streak" -ge "$_lat_debounce" ]; then
                    append_event "high_latency" \
                        "High latency detected (avg ${conn_avg_latency}ms, last ${conn_latency}ms)" "warning"
                    ev_lat_alerted=true
                    ev_high_lat_streak=0
                fi
            fi
        else
            ev_high_lat_streak=0
            if [ "$ev_lat_alerted" = "true" ]; then
                ev_lat_clear_streak=$((ev_lat_clear_streak + 1))
                if [ "$ev_lat_clear_streak" -ge "$_lat_debounce" ]; then
                    append_event "latency_recovered" \
                        "Latency recovered (avg ${conn_avg_latency}ms)" "info"
                    ev_lat_alerted=false
                    ev_lat_clear_streak=0
                fi
            fi
        fi
    fi

    # --- Packet loss: same shape ---
    local _loss_threshold="${QUALITY_LOSS_THRESHOLD:-30}"
    local _loss_debounce="${QUALITY_LOSS_DEBOUNCE:-3}"
    case "$conn_packet_loss" in
        ''|null|*[!0-9]*) ;;
        *)
            if [ "$conn_packet_loss" -ge "$_loss_threshold" ] 2>/dev/null; then
                ev_loss_clear_streak=0
                if [ "$_held" = "1" ]; then
                    ev_high_loss_streak=0
                elif [ "$ev_loss_alerted" != "true" ]; then
                    ev_high_loss_streak=$((ev_high_loss_streak + 1))
                    if [ "$ev_high_loss_streak" -ge "$_loss_debounce" ]; then
                        append_event "high_packet_loss" \
                            "High packet loss detected (${conn_packet_loss}%)" "warning"
                        ev_loss_alerted=true
                        ev_high_loss_streak=0
                    fi
                fi
            else
                ev_high_loss_streak=0
                if [ "$ev_loss_alerted" = "true" ]; then
                    ev_loss_clear_streak=$((ev_loss_clear_streak + 1))
                    if [ "$ev_loss_clear_streak" -ge "$_loss_debounce" ]; then
                        append_event "packet_loss_recovered" \
                            "Packet loss recovered (${conn_packet_loss}%)" "info"
                        ev_loss_alerted=false
                        ev_loss_clear_streak=0
                    fi
                fi
            fi ;;
    esac
}

# Compare current state vs previous and emit events for any changes
detect_events() {
    # First cycle: populate previous state, don't generate events
    if [ "$events_initialized" = "false" ]; then
        snapshot_event_state
        # Initialize PCI state file with current SCCs
        if [ -n "$t2_carrier_components" ] && [ "$t2_carrier_components" != "[]" ]; then
            printf '%s' "$t2_carrier_components" | \
                jq -c '[.[] | select(.type == "SCC") | {tech: .technology, band: .band, pci: .pci}]' \
                > "$PCI_STATE_FILE" 2>/dev/null
        fi
        events_initialized=true
        qlog_debug "Event detection initialized"
        return
    fi

    # =====================================================================
    # Section 1: Network Mode events
    # =====================================================================

    # --- Modem reachability ---
    if [ "$modem_reachable" != "$prev_ev_modem_reachable" ]; then
        if [ "$modem_reachable" = "true" ]; then
            local net_ctx
            _ev_net_context_set
            net_ctx="$_EV_CTX"
            local restore_detail=""
            [ -n "$net_ctx" ] && restore_detail=" — $net_ctx"
            append_event "signal_restored" "Modem signal restored${restore_detail}" "info"
        else
            append_event "signal_lost" "Modem became unreachable" "warning"
            # Don't generate band/PCI events when modem goes away
            snapshot_event_state
            return
        fi
    fi

    # Skip detailed checks if modem is unreachable
    if [ "$modem_reachable" != "true" ]; then
        snapshot_event_state
        return
    fi

    # --- Airplane mode (CFUN transition) ---
    if [ "$t1_cfun" != "$prev_ev_cfun" ]; then
        if [ "$prev_ev_cfun" = "1" ] && { [ "$t1_cfun" = "0" ] || [ "$t1_cfun" = "4" ]; }; then
            append_event "airplane_mode" "Airplane mode enabled (CFUN=$t1_cfun)" "warning"
        elif { [ "$prev_ev_cfun" = "0" ] || [ "$prev_ev_cfun" = "4" ]; } && [ "$t1_cfun" = "1" ]; then
            append_event "airplane_mode" "Airplane mode disabled" "info"
        fi
    fi

    # --- Network mode change ---
    if [ -n "$network_type" ] && [ -n "$prev_ev_network_type" ] && \
       [ "$network_type" != "$prev_ev_network_type" ]; then
        # Determine if upgrade or downgrade: 5G-SA > 5G-NSA > LTE
        local mode_severity="info"
        case "$prev_ev_network_type-$network_type" in
            5G-SA-5G-NSA|5G-SA-LTE|5G-NSA-LTE) mode_severity="warning" ;;
        esac
        # Include current band context
        local mode_detail=""
        case "$network_type" in
            5G-NSA)
                [ -n "$lte_band" ] && [ -n "$nr_band" ] && mode_detail=" (${lte_band} + ${nr_band})"
                ;;
            5G-SA)
                [ -n "$nr_band" ] && mode_detail=" (${nr_band})"
                ;;
            LTE)
                [ -n "$lte_band" ] && mode_detail=" (${lte_band})"
                ;;
        esac
        append_event "network_mode" \
            "Network mode changed from $prev_ev_network_type to $network_type${mode_detail}" "$mode_severity"
    fi

    # =====================================================================
    # Section 2: Band Changes events
    # =====================================================================

    # Band and PCI go through _ev_settle: on a drop the modem walks a ladder of
    # coverage bands for a sample or two each before settling back, and a raw
    # sample-to-sample inequality reported every rung (and, with blanks in the
    # baseline, dropped the return leg). A blank is no observation. Messages
    # say "settled on X (was Y)" because the intermediate rungs are skipped.
    local _rc

    # --- LTE band change (settle-debounced) ---
    _ev_settle lte_band "$lte_band"; _rc=$?
    if [ "$_rc" -eq 0 ]; then
        local lte_band_detail=""
        [ -n "$lte_pci" ] && lte_band_detail=" (PCI $lte_pci)"
        append_event "band_change"             "LTE band settled on ${_EV_SETTLED_TO} (was ${_EV_SETTLED_FROM})${lte_band_detail}" "info"
    elif [ "$_rc" -eq 2 ]; then
        append_event "band_change"             "LTE band unstable (${_EV_FLAP_N} changes in the last $((EV_FLAP_WINDOW / 60)) min)" "warning"
    fi

    # --- LTE PCI change (PCC cell handoff, settle-debounced) ---
    _ev_settle lte_pci "$lte_pci"; _rc=$?
    if [ "$_rc" -eq 0 ]; then
        local lte_pci_ctx=""
        [ -n "$lte_band" ] && lte_pci_ctx=" on $lte_band"
        append_event "pci_change"             "LTE PCC cell handoff${lte_pci_ctx} (PCI: ${_EV_SETTLED_FROM} -> ${_EV_SETTLED_TO})" "info"
    elif [ "$_rc" -eq 2 ]; then
        append_event "pci_change"             "LTE cell unstable (${_EV_FLAP_N} handoffs in the last $((EV_FLAP_WINDOW / 60)) min)" "warning"
    fi

    # --- NR state change (5G anchor gained/lost) ---
    if [ -n "$nr_state" ] && [ -n "$prev_ev_nr_state" ] && \
       [ "$nr_state" != "$prev_ev_nr_state" ]; then
        if [ "$nr_state" = "connected" ] && [ "$prev_ev_nr_state" != "connected" ]; then
            local nr_anchor_detail="($nr_band)"
            [ -n "$nr_pci" ] && nr_anchor_detail="($nr_band, PCI $nr_pci)"
            append_event "nr_anchor" "5G NR anchor acquired $nr_anchor_detail" "info"
        elif [ "$nr_state" != "connected" ] && [ "$prev_ev_nr_state" = "connected" ]; then
            local nr_lost_detail=""
            [ -n "$prev_ev_nr_band" ] && nr_lost_detail=" (was $prev_ev_nr_band)"
            append_event "nr_anchor" "5G NR anchor lost${nr_lost_detail}" "warning"
        fi
    fi

    # --- NR band / PCI changes (settle-debounced) ---
    # While the NR anchor is down there is nothing to observe: feed a blank so
    # the counters freeze rather than reset, and an NSA drop-and-reacquire onto
    # the same band stays silent (the anchor events above report the drop).
    local _nr_band_obs="" _nr_pci_obs=""
    if [ "$nr_state" = "connected" ]; then
        _nr_band_obs="$nr_band"
        _nr_pci_obs="$nr_pci"
    fi

    _ev_settle nr_band "$_nr_band_obs"; _rc=$?
    if [ "$_rc" -eq 0 ]; then
        local nr_band_detail=""
        [ -n "$nr_pci" ] && nr_band_detail=" (PCI $nr_pci)"
        append_event "band_change"             "NR band settled on ${_EV_SETTLED_TO} (was ${_EV_SETTLED_FROM})${nr_band_detail}" "info"
    elif [ "$_rc" -eq 2 ]; then
        append_event "band_change"             "NR band unstable (${_EV_FLAP_N} changes in the last $((EV_FLAP_WINDOW / 60)) min)" "warning"
    fi

    _ev_settle nr_pci "$_nr_pci_obs"; _rc=$?
    if [ "$_rc" -eq 0 ]; then
        local nr_pci_ctx=""
        [ -n "$nr_band" ] && nr_pci_ctx=" on $nr_band"
        append_event "pci_change"             "NR PCC cell handoff${nr_pci_ctx} (PCI: ${_EV_SETTLED_FROM} -> ${_EV_SETTLED_TO})" "info"
    elif [ "$_rc" -eq 2 ]; then
        append_event "pci_change"             "NR cell unstable (${_EV_FLAP_N} handoffs in the last $((EV_FLAP_WINDOW / 60)) min)" "warning"
    fi

    # --- CA changes (sticky settle, see _ev_ca_check) ---
    _ev_ca_check lte_ca LTE "$t2_ca_count"
    _ev_ca_check nr_ca NR "$t2_nr_ca_count"

    # --- SCC PCI changes ---
    # Keyed on the SCC tech/band/PCI set only. The whole carrier string also
    # carries RSRP/RSRQ/SINR, so comparing it ran the jq-heavy detector on
    # almost every active cycle without anything to report.
    _ev_scc_sig "$t2_carrier_components"
    if [ "$_EV_SCC_SIG" != "$prev_ev_scc_sig" ]; then
        detect_scc_pci_changes
    fi

    # Data connection events run from the poller every cycle, right after
    # read_ping_data (they need no modem), not from here.

    # Update snapshot
    snapshot_event_state
}
